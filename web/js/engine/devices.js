'use strict';
// Модели приборов поверх голого решателя.
//
// Решатель знает только резистор, источник, ключ, конденсатор, катушку,
// диод и транзистор. Настоящий прибор из них складывается — и складывать
// его надо один раз здесь, а не заново в каждом уровне.

// Светодиод. Голый диод решателя открывается около 0,6 В — это кремниевый
// диод, а не светодиод: у красного светодиода прямое падение ~1,8 В, и от
// одной батарейки 1,5 В он в принципе не загорится. Поэтому модель —
// диод плюс постоянное смещение до нужного порога плюс небольшое
// собственное сопротивление кристалла (через него же деталь размыкается,
// когда сгорит).
function addLed(c, a, b, name, vf = 1.8) {
  const mid1 = name + '_M1';
  const mid2 = name + '_M2';
  c.addVoltageSource(a, mid1, Math.max(vf - 0.62, 0.0), name + '_VF');
  c.addDiode(mid1, mid2, name + '_D');
  return c.addResistor(mid2, b, 4.0, name);
}

// Лампа накаливания — сопротивление нити. Холодная нить у настоящей лампы
// в разы легче горячей; для уровней прототипа берём номинальное горячее
// сопротивление и не моделируем пусковой бросок.
function addLamp(c, a, b, ohms, name) {
  return c.addResistor(a, b, ohms, name);
}

// Мотор на постоянном токе: сопротивление обмотки. Противо-ЭДС не
// моделируем — мотор в уровнях либо крутится, либо нет, разгон не важен.
function addMotor(c, a, b, ohms, name) {
  return c.addResistor(a, b, ohms, name);
}

// Реле. Катушка — обычный резистор, а контакт — обычный ключ; связь между
// ними не электрическая, а механическая, и живёт вне матрицы: каждый шаг
// смотрим ток катушки и решаем, притянут якорь или отпущен.
// Гистерезис настоящий: отпускает реле при меньшем токе, чем срабатывает.
function makeRelay(c, coilA, coilB, contactA, contactB, name, opts = {}) {
  const coil = c.addResistor(coilA, coilB, opts.coilOhms || 400, name + '_COIL');
  const contact = c.addSwitch(contactA, contactB, false, name + '_C');
  return {
    coil,
    contact,
    pullIn: opts.pullIn || 0.012,
    dropOut: opts.dropOut || 0.006,
    closed: false,
    pull: 0,
    // Вызывается уровнем каждый шаг: механика якоря, а не электрика.
    update(circuit, coilCurrent, dt) {
      const i = Math.abs(coilCurrent);
      if (!this.closed && i > this.pullIn) this.closed = true;
      else if (this.closed && i < this.dropOut) this.closed = false;
      circuit.setSwitch(this.contact, this.closed);
      this.pull = approach(this.pull, this.closed ? 1 : 0, 30, dt);
      return this.closed;
    },
  };
}

// Источник питания с внутренним сопротивлением — то есть настоящий.
//
// Идеальный источник держит своё напряжение под любой нагрузкой: повесь на
// него хоть короткое замыкание, на клеммах всё равно будет двенадцать
// вольт. Так не бывает ни у одной батарейки и ни у одного блока питания.
// У любого источника внутри есть сопротивление, и как только кто-то на
// шине начинает брать много тока, напряжение проседает — сразу у всех, кто
// на этой же шине сидит.
//
// Из-за этого схема перестаёт быть набором независимых кусков: сильная
// нагрузка притапливает слабых соседей, и это видно на приборах. Порядок
// величин настоящий: пальчиковый элемент ~0,2 Ом, «крона» ~1,7 Ом (она и в
// жизни проседает заметнее всех), блок питания прибора ~0,3–0,5 Ом.
//
// Ток источника по-прежнему читается под именем `name`, а узел `a` — это
// клемма, на которой напряжение уже просело.
// Порядки внутреннего сопротивления настоящих источников — чтобы не
// придумывать их на глаз в каждом уровне заново. Курс: пальчиковый элемент
// свежий держит нагрузку почти как идеальный, а вот «крона» из-за своей
// маленькой и плотной конструкции просаживается заметно сильнее любого
// другого источника в игре — с ней это виднее всего.
const SUPPLY_R = {
  AA_CELL: 0.2,   // пальчиковый элемент 1,5 В
  KRONA: 1.7,     // «крона» 9 В — самая «мягкая» из источников игры
  BENCH: 0.4,     // блок питания/аккумуляторная шина прибора
};

function addSupply(c, a, b, volts, name, rInt) {
  const inner = name + '_INT';
  const source = c.addVoltageSource(inner, b, volts, name);
  c.addResistor(inner, a, Math.max(rInt || 0, 1e-6), name + '_RINT');
  return source;
}
