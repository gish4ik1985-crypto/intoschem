'use strict';
// Композиция узлов: пройденный уровень как деталь. План и границы — в
// BLOCKS.md, читать перед тем как трогать этот файл.
//
// Формат блока сознательно зеркалит формат уровня, а не изобретает свой:
// `build(c, netAt)` — то же самое, что `build(c)` у обычного уровня
// (`createLevel`), только вместо голых строк-имён сетей зовёт `netAt(name)`.
// `netAt` подставляет ЛИБО ту внешнюю сеть, к которой блок сейчас подключён
// (если `name` — один из `terminals`), ЛИБО внутреннюю сеть, размеченную
// под конкретный экземпляр блока на плате (если `name` — что-то своё,
// не выведенное наружу). Кто и как считает `netAt` — дело
// `Blocks.instantiate` (следующий пункт чек-листа в BLOCKS.md, этот файл
// его ещё не реализует). Здесь только сам реестр и данные блока: без этого
// разделения два экземпляра одного блока на одной плате слились бы
// внутренней серединой в один узел решателя.
//
// Деталь блока на плате не хранит НИЧЕГО из parts/wires обычного уровня —
// изнутри блок игроку не виден (см. «явные НЕ-цели» в BLOCKS.md: блок —
// готовый инструмент, а не разводка для повторного разглядывания).
// `terminals`/`hit` нужны только для отрисовки корпуса и для хит-теста
// проводов игрока снаружи, тем же способом, каким Parts.* описывает любую
// другую деталь.

const BlockRegistry = {
  list: [],
  register(def) {
    this.list.push(def);
    return def;
  },
  byId(id) { return this.list.find((b) => b.id === id); },
};

// Пилотный блок — опорный делитель 3,6 В из уровня `divider`
// (web/js/levels/l06_divider.js, сектор А). Номиналы НЕ читаются из
// партии игрока: это canonical-решение, которое сам урок называет в
// lesson/hints («отношение 3 к 2», «сумма в несколько сотен ом»).
// R1=150, R2=100 — оба в RESISTOR_KIT (web/js/levels/_kit.js), с идеальным
// источником дают ровно 9 × 100/250 = 3,6 В, центр требуемого окна
// уровня-донора (3,4–3,8 В). См. BLOCKS.md, «Кандидат на пилотный блок».
BlockRegistry.register({
  id: 'divider_block',
  title: 'Опорный делитель 3,6 В',
  // id уровня, первое прохождение которого открывает блок игроку.
  unlockedBy: 'divider',
  silk: 'BLK-DIV',
  hit: { w: 72, h: 56 },
  // Локальные координаты выводов относительно центра детали — тот же вид,
  // что у terminals() любой обычной детали в Parts. |x| у всех трёх больше
  // половины ширины корпуса (36) — вывод снаружи коробки, с коротким
  // отводом до её края, как у любой другой детали (см. Parts.block.draw).
  terminals: { plus: vec(-44, -20), minus: vec(-44, 20), out: vec(44, 0) },

  build(c, netAt) {
    // netAt используется и для сетей, и для имён компонентов решателя:
    // 'plus'/'minus'/'out' — объявленные выводы, подставляются наружу;
    // 'R1'/'R2' — не выводы, значит namespace'ится под конкретный
    // экземпляр блока (part.id + ':R1') — без этого два делителя на одной
    // плате завели бы решателю два компонента с одинаковым именем 'R1' и
    // столкнулись бы в componentCurrent.
    const r1 = c.addResistor(netAt('plus'), netAt('out'), 150, netAt('R1'));
    const r2 = c.addResistor(netAt('out'), netAt('minus'), 100, netAt('R2'));
    return { R1: r1, R2: r2 };
  },
});

// Заводит один экземпляр блока в цепь: разбирает его на настоящие детали
// решателя (см. комментарий вверху файла и BLOCKS.md, «Физика блока»).
// Зовётся из rebuildFreeform в level.js для каждой детали kind==='block'.
const Blocks = {
  instantiate(circuit, part) {
    const def = BlockRegistry.byId(part.blockId);
    if (!def) return null;
    const netAt = (name) => (def.terminals[name] !== undefined
      ? part.blockNets[name]
      : part.id + ':' + name);
    return def.build(circuit, netAt);
  },
};
