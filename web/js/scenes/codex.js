const CodexPanel = (() => {
  // Кодекс читают, не отвлекаясь на часы: время в схеме должно стоять,
  // иначе деталь догорит или конденсатор дозарядится, пока игрок читает
  // статью, а он даже не видит, что происходит на плате в это время.
  function openOverlay(highlight) {
    SceneManager.paused = true;
    const back = el('div', 'codex', uiLayer());
    el('div', 'codex-head', back).textContent = 'Кодекс';
    el('div', 'codex-sub', back).textContent = 'Детали, законы и то, зачем они вообще нужны';

    const body = el('div', 'codex-body', back);
    const nav = el('div', 'codex-nav', body);
    const article = el('div', 'codex-article', body);

    const closeBtn = makeButton('Закрыть', () => { back.remove(); SceneManager.paused = false; }, 'btn-ghost codex-close');
    back.appendChild(closeBtn);

    const buttons = {};
    function show(id) {
      const a = CodexData.articles.find((x) => x.id === id);
      if (!a) return;
      for (const k of Object.keys(buttons)) buttons[k].classList.toggle('is-active', k === id);
      let html = '<div class="codex-art-title">' + a.title + '</div>';
      html += '<div class="codex-art-lead">' + a.lead + '</div>';
      for (const [label, bodyText] of a.fields) {
        html += '<div class="codex-field-label">' + label + '</div>';
        html += '<div class="codex-field-body">' + bodyText + '</div>';
      }
      article.innerHTML = html;
      article.scrollTop = 0;
    }

    for (const sec of CodexData.sections) {
      el('div', 'codex-sec', nav).textContent = sec.title;
      for (const a of CodexData.articles.filter((x) => x.sec === sec.id)) {
        const b = makeButton(a.title, () => show(a.id), 'btn-ghost');
        if (highlight && highlight.includes(a.id)) b.classList.add('is-active');
        buttons[a.id] = b;
        nav.appendChild(b);
      }
    }

    show(highlight && highlight.length ? highlight[0] : CodexData.articles[0].id);
    return back;
  }

  return { openOverlay };
})();
