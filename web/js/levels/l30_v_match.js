'use strict';
// В-05 · Согласование. Единственный узел, где «чем меньше сопротивление, тем
// больше мощность» перестаёт работать: максимум лежит посередине, и найти его
// можно только потому, что источник в этой игре честный.

(() => {
  const LOAD_KIT = [1, 2.2, 4.7, 10, 22, 47];
  const L = Rig.rows({
    id: 'v_match',
    board: DB.s.board,
    supply: { id: 'SUP', name: 'Изношенный элемент', label: '9 В', silk: 'G1', value: 9.0, rInt: 4.7 },
    rated: 1.2,
    rows: [
      {
        id: 'LD', rated: 1.2,
        items: [deckSocket('RL', 'Гнездо нагрузки', { silk: 'RL', title: 'Какую нагрузку подключить', jumper: false, kit: LOAD_KIT, rated: { pMax: 8.0, tau: 2.0 } })],
      },
    ],
  });

  createLevel(LevelRegistry.register({
    id: 'v_match',
    index: 44,
    title: 'Согласование нагрузки',
    teaches: 'максимум мощности в нагрузке',
    silk: 'MCH-047-30',
    diag: 'ДИАГНОСТИКА · Узел В-05: от источника надо снять максимум мощности, элемент изношен.',
    brief: 'Источник этого узла давно выработал ресурс: внутри у него теперь заметное сопротивление, и напряжение на клеммах проседает от любой нагрузки. Задача — снять с него наибольшую возможную мощность. Не наибольший ток. Мощность.',
    lesson: 'Уменьшая нагрузку, ток наращиваешь, но напряжение на клеммах проседает — и произведение одного на другое сначала растёт, а потом начинает падать. Максимум лежит ровно там, где сопротивление нагрузки равно внутреннему сопротивлению источника. Цена известна заранее: в этой точке ровно столько же мощности греет сам источник изнутри, то есть половина уходит впустую. Поэтому так делают там, где важно снять максимум, а не там, где важен КПД.',
    reveal: 'Резервный элемент аварийного питания. Он не разряжен — он состарился: заряд остался, а отдать его быстро уже не может.',
    hints: [
      'Пройди по номиналам подряд и запиши мощность для каждого — она сначала растёт, потом падает.',
      'Смотри не на ток и не на напряжение по отдельности, а на их произведение.',
      'Наведи курсор на источник: разница между паспортными девятью вольтами и тем, что на клеммах, — это и есть падение на его внутреннем сопротивлении.',
    ],
    codex: ['battery', 'power', 'ohm', 'short', 'resistor'],
    vmax: 9.0,
    hold: 2.5,
    scale: DB.s.scale,
    board: DB.s.board,
    map: { pos: vec(538, -135), radius: 900, color: hex(0xff9a3c), from: ['v_bridge', 'v_trim'], icon: { kind: 'krona' } },
    goalText: 'Снять с источника не меньше 4,2 Вт.',
    scope: { label: 'Мощность в нагрузке', get: (m) => m.pLoad, min: 0, max: 5, band: [4.2, 4.4], fmt: fmtWatts },

    parts: L.parts,
    wires: L.wires,
    build: (c, P) => Rig.build(c, P),
    apply: (refs, P, c) => Rig.apply(c, refs, P),

    read(sol, refs, P) {
      const uOut = sol.nodeVoltage.VCC || 0;
      const i = Math.abs(sol.componentCurrent.RL || 0);
      return {
        uOut, i,
        pLoad: uOut * i,
        pInside: (9.0 - uOut) * i,
        rl: P.RL.content ? P.RL.content.value : NaN,
        empty: !P.RL.content,
        ok: uOut * i >= 4.2,
      };
    },

    status(m) {
      if (m.empty) return ['Гнездо нагрузки пустое — источник ничего не отдаёт.', 'neutral'];
      if (m.ok) return ['Максимум снят: нагрузка сравнялась с внутренним сопротивлением источника.', 'good'];
      if (m.rl < 4) return ['Нагрузка слишком мала: ток большой, но клеммы просели, и мощность падает.', 'warn'];
      return ['Нагрузка слишком велика: напряжение почти паспортное, но тока мало.', 'warn'];
    },

    goal(m) {
      if (m.empty) return { ok: false, note: 'Нагрузка не подключена.' };
      return { ok: m.ok, note: 'В нагрузке ' + fmtWatts(m.pLoad) + ', нужно не меньше 4,2 Вт' };
    },

    score(m) { return m.empty ? 0 : clamp(m.pLoad / 4.31, 0, 1); },
    scoreNote(m) { return 'В нагрузке ' + fmtWatts(m.pLoad) + ', и ровно столько же греет сам источник изнутри'; },

    meter(m) {
      return [
        ['Мощность в нагрузке', fmtWatts(m.pLoad), m.ok ? 'good' : 'warn'],
        ['Греет сам источник', fmtWatts(m.pInside)],
        ['На клеммах', fmtVolts(m.uOut)],
        ['Ток', fmtAmps(m.i)],
        ['Нагрузка', fmtOhms(m.rl)],
      ];
    },
  }));
})();
