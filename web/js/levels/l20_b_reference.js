'use strict';
// Б-12 · Делитель под нагрузкой. Первый узел, где «посчитал на бумаге» и
// «померил на плате» дают разные числа — и это не ошибка прибора.
//
// Потребитель здесь импульсный, и это не украшение: если нагрузка постоянна,
// делитель можно подогнать ПОД НЕЁ (взять нижнее плечо с учётом её
// сопротивления) — опора будет ровно шесть вольт, и урок не состоится. Ровно
// это и вылезло при первой сборке узла: перебор нашёл шесть проходных
// вариантов, и самый «красивый» из них разваливался, стоило потребителю
// отключиться. Нагрузка, которая приходит и уходит, оставляет только один
// честный ответ — плечи много меньше нагрузки.

(() => {
  const L = Rig.rows({
    id: 'b_reference',
    board: DB.l.board,
    busX: { REF: 0.35 },
    supply: { id: 'SUP', name: 'Ввод узла', label: '12 В', silk: 'G1', value: 12 },
    rows: [
      {
        id: 'TOP', to: 'REF', rated: 0.3,
        items: [deckSocket('R1', 'Верхнее плечо', { silk: 'R1', title: 'Верхнее плечо делителя', jumper: false, rated: { pMax: 2.0, tau: 1.0 } })],
      },
      {
        id: 'BOT', from: 'REF', rated: 0.3,
        items: [deckSocket('R2', 'Нижнее плечо', { silk: 'R2', title: 'Нижнее плечо делителя', jumper: false, rated: { pMax: 2.0, tau: 1.0 } })],
      },
      {
        id: 'LD', from: 'REF', rated: 0.05,
        items: [
          // Ключом потребителя щёлкает он сам — игрок его не трогает.
          { id: 'K1', kind: 'toggle', name: 'Ключ потребителя', silk: 'K1', closed: false },
          { id: 'RL', kind: 'device', name: 'Импульсный потребитель', silk: 'RL', value: 470, rated: { pMax: 1.5, tau: 1.0 } },
        ],
      },
    ],
  });

  createLevel(LevelRegistry.register({
    id: 'b_reference',
    index: 34,
    title: 'Опорное напряжение',
    teaches: 'делитель под нагрузкой',
    silk: 'REF-06-20',
    diag: 'ДИАГНОСТИКА · Узел Б-12: опора дёргается в такт работе потребителя.',
    brief: 'Узел раздаёт соседу половину шины. Оба плеча делителя вынуты из гнёзд. Потребитель включается и выключается сам, примерно два раза в секунду, и опора обязана оставаться шестью вольтами в обоих случаях — и когда он берёт ток, и когда не берёт.',
    lesson: 'Делитель без нагрузки честно делит по формуле. Но подключённый потребитель встаёт параллельно нижнему плечу и уменьшает его — опора проседает. Подогнать делитель под нагрузку можно, только пока она постоянна; стоит ей уйти, и подгонка разваливается. Настоящий выход один: плечи должны быть много меньше нагрузки, чтобы её появление на их фоне терялось. Плата за это — ток, который делитель греет впустую сам на себе.',
    reveal: 'Опора измерительного тракта. Всё, что этот узел раздаёт, потом сравнивают с ним — и если опора врёт, врут и все измерения изделия сразу.',
    hints: [
      'Смотри на ленту самописца: видно, как опора дёргается в такт потребителю.',
      'Когда потребитель включён, он стоит параллельно нижнему плечу. Посчитай нижнее плечо вместе с ним — и сравни с тем, что было без него.',
      'Чем меньше плечи по сравнению с нагрузкой, тем меньше она их портит. Но тем больше делитель греется впустую — следи за нагревом.',
    ],
    codex: ['divider', 'ohm', 'series', 'power', 'resistor'],
    vmax: 12.0,
    hold: 3.0,
    scale: DB.l.scale,
    board: DB.l.board,
    map: { pos: vec(-322, -135), radius: 900, color: hex(0x2fd4c8), from: ['switchboard', 'b_ballast'], icon: { kind: 'resistor', value: 47 } },
    goalText: 'Опора 6 В (допуск ±5%) и когда потребитель включён, и когда выключен.',
    scope: { label: 'Опорное напряжение', get: (m) => m.ref, min: 4, max: 8, band: [5.7, 6.3], fmt: fmtVolts },

    parts: L.parts,
    wires: L.wires,
    build: (c, P) => Rig.build(c, P),
    apply: (refs, P, c) => Rig.apply(c, refs, P),

    // Потребитель работает импульсами — это и есть проверка узла.
    tick(dt, P) {
      P.K1.phase = ((P.K1.phase || 0) + dt) % 1.2;
      P.K1.closed = P.K1.phase < 0.6;
    },

    read(sol, refs, P) {
      const ref = sol.nodeVoltage.REF || 0;
      return {
        ref,
        loaded: !!P.K1.closed,
        iTop: Math.abs(sol.componentCurrent.R1 || 0),
        iLoad: Math.abs(sol.componentCurrent.RL || 0),
        heat: Math.max(P.R1.heat || 0, P.R2.heat || 0),
        empty: !P.R1.content || !P.R2.content,
        inBand: inPct(ref, 6.0, 0.05),
      };
    },

    status(m) {
      if (m.empty) return ['Одно из плеч делителя пустое — опоры нет вообще.', 'neutral'];
      if (m.inBand && m.heat > 0.8) return ['Опора держится, но плечи раскалены: они греются впустую собственным током.', 'warn'];
      if (m.inBand) return ['Шесть вольт. Потребитель приходит и уходит, а опора стоит.', 'good'];
      if (m.ref < 5.7) return ['Опора просела: потребитель встал параллельно нижнему плечу и утянул её вниз.', 'warn'];
      return ['Опора ушла вверх: без потребителя нижнее плечо ничем не нагружено.', 'warn'];
    },

    goal(m) {
      return {
        ok: m.inBand,
        note: 'Опора ' + fmtVolts(m.ref) + ' (' + (m.loaded ? 'потребитель включён' : 'потребитель выключен') + '), нужно 6 В в обоих случаях',
      };
    },

    score(m) { return bandScore(m.ref, 6.0, 0.05); },
    scoreNote(m) { return 'Опора ' + fmtVolts(m.ref) + ' независимо от потребителя; сам делитель тянет ' + fmtAmps(m.iTop); },

    meter(m) {
      return [
        ['Опора', fmtVolts(m.ref), m.inBand ? 'good' : 'warn'],
        ['Потребитель', m.loaded ? 'берёт ток' : 'отключился', ''],
        ['Ток верхнего плеча', fmtAmps(m.iTop)],
        ['Ток потребителя', fmtAmps(m.iLoad)],
        ['Нагрев плеч', Math.round(clamp(m.heat, 0, 1) * 100) + '%', m.heat > 0.8 ? 'bad' : ''],
      ];
    },
  }));
})();
