'use strict';
// Б-16 · Бросок при включении. Конденсатор в момент включения ведёт себя как
// короткое замыкание — и ток в первый миг ограничивает только то, что стоит
// перед ним. Числа, которые тут надо развести, тянут в разные стороны, и это
// главное, ради чего узел собран.

(() => {
  const L = Rig.rows({
    id: 'b_inrush',
    board: DB.l.board,
    busX: { BUS: 0.62 },
    supply: { id: 'SUP', name: 'Ввод узла', label: '12 В', silk: 'G1', value: 12 },
    rows: [
      {
        id: 'IN', to: 'BUS', rated: 0.5,
        items: [
          deckToggle('SA1', 'Ключ ввода', false, 'Нажми, чтобы подать питание на узел'),
          deckSocket('R0', 'Токоограничитель', { silk: 'R0', title: 'Что ограничивает бросок', jumper: false, rated: { pMax: 4.0, tau: 1.2 } }),
        ],
      },
      {
        id: 'CP', from: 'BUS', rated: 0.5,
        items: [{ id: 'C1', kind: 'capacitor', name: 'Накопитель шины', silk: 'C1', value: 4700e-6, vMax: 16, label: '4700 мкФ' }],
      },
      {
        id: 'LP', from: 'BUS', rated: 0.25,
        items: [{ id: 'HL1', kind: 'lamp', name: 'Нагрузка узла', silk: 'HL1', value: 30, rated: { pNom: 1.6, pMax: 4.0, tau: 1.0 } }],
      },
    ],
  });

  createLevel(LevelRegistry.register({
    id: 'b_inrush',
    index: 38,
    title: 'Бросок при включении',
    teaches: 'конденсатор в первый миг',
    silk: 'INR-47-24',
    diag: 'ДИАГНОСТИКА · Узел Б-16: в момент включения ток кратковременно уходит далеко за норму.',
    brief: 'На шине узла стоит накопитель. Паспорт запрещает бросок тока больше 550 мА в момент включения и требует, чтобы после этого на нагрузке было не меньше 6,5 В. Гнездо токоограничителя пустое.',
    lesson: 'Пустой конденсатор в первый миг ничем не отличается от короткого замыкания: напряжения на нём ещё нет, и ток ограничивает только то, что стоит перед ним. Потом он набирается, и всё приходит в норму. Поэтому токоограничитель выбирают сразу по двум условиям, которые тянут в разные стороны: больше — меньше бросок, но меньше остаётся нагрузке.',
    reveal: 'Ввод накопительной шины. Накопитель держал питание в те доли секунды, когда основная линия проваливалась. Судя по его состоянию, проваливалась она часто.',
    hints: [
      'Включи ключ и смотри на ленту самописца: пик тока живёт доли секунды.',
      'В первый миг конденсатор пуст, и весь ток ограничивает только токоограничитель: двенадцать вольт делить на его сопротивление.',
      'Слишком большой токоограничитель уберёт бросок, но заберёт себе вольты, которые нужны нагрузке. Ищи номинал, при котором проходят оба условия.',
    ],
    codex: ['capacitor', 'rc', 'ohm', 'power', 'lamp'],
    vmax: 12.0,
    hold: 2.5,
    scale: DB.l.scale,
    board: DB.l.board,
    map: { pos: vec(-967, 30), radius: 900, color: hex(0x8fd0ff), from: ['workbench', 'b_split'], icon: { kind: 'capacitor', value: 4700e-6 } },
    goalText: 'Бросок не выше 550 мА, и на нагрузке не меньше 6,5 В.',
    scope: { label: 'Ток через токоограничитель', get: (m) => m.i0, min: 0, max: 1.2, band: [0, 0.55], fmt: fmtAmps },

    parts: L.parts,
    wires: L.wires,
    build: (c, P) => Rig.build(c, P),
    apply: (refs, P, c) => Rig.apply(c, refs, P),

    // Пик живёт доли кадра: его пишет каркас внутри шагов решателя (iMax).
    // Разомкнутый ключ обнуляет счёт — иначе неудачная первая попытка
    // навсегда осталась бы в памяти узла и уровень стал бы непроходимым.
    tick(dt, P) {
      if (!P.SA1.closed) { P.R0.iMax = 0; P.HL1.iMax = 0; }
    },

    read(sol, refs, P) {
      const uBus = sol.nodeVoltage.BUS || 0;
      const peak = P.R0.iMax || 0;
      return {
        uBus,
        i0: Math.abs(sol.componentCurrent.R0 || 0),
        iLamp: Math.abs(sol.componentCurrent.HL1 || 0),
        peak,
        on: !!P.SA1.closed,
        empty: !P.R0.content,
        charge: clamp(uBus / 12, 0, 1),
        peakOk: peak > 0 && peak <= 0.55,
        uOk: uBus >= 6.5,
      };
    },

    status(m) {
      if (m.empty) return ['Токоограничитель не поставлен — ветка разомкнута.', 'neutral'];
      if (!m.on) return ['Ключ ввода разомкнут. Замкни его и смотри на ленту: бросок живёт доли секунды.', 'neutral'];
      if (!m.peakOk) return ['Бросок был ' + fmtAmps(m.peak) + ' — выше разрешённых 550 мА. Токоограничитель слишком мал.', 'bad'];
      if (!m.uOk) return ['Бросок в норме, но нагрузке достаётся всего ' + fmtVolts(m.uBus) + ': токоограничитель забрал себе слишком много.', 'warn'];
      return ['Бросок укладывается, и на нагрузке хватает напряжения.', 'good'];
    },

    goal(m) {
      if (!m.on) return { ok: false, note: 'Ключ ввода разомкнут — броска ещё не было.' };
      if (!m.peakOk) return { ok: false, note: 'Бросок ' + fmtAmps(m.peak) + ', разрешено 550 мА' };
      return { ok: m.uOk, note: 'На нагрузке ' + fmtVolts(m.uBus) + ', нужно не меньше 6,5 В' };
    },

    score(m) { return (m.on && m.peakOk) ? bandScore(m.uBus, 6.87, 0.12) : 0; },
    scoreNote(m) { return 'Бросок ' + fmtAmps(m.peak) + ' при разрешённых 550 мА, на нагрузке ' + fmtVolts(m.uBus); },

    meter(m) {
      return [
        ['Бросок при включении', m.peak > 0 ? fmtAmps(m.peak) : '—', m.peakOk ? 'good' : (m.peak > 0 ? 'bad' : '')],
        ['Ток сейчас', fmtAmps(m.i0)],
        ['На нагрузке', fmtVolts(m.uBus), m.uOk ? 'good' : 'warn'],
        ['Накопитель набран', Math.round(m.charge * 100) + '%'],
        ['Разрешено', '550 мА · не ниже 6,5 В'],
      ];
    },
  }));
})();
