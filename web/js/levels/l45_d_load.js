'use strict';
// Д-05 · Привод с меняющейся нагрузкой. Балласт один, а режимов два — и
// подобрать его надо так, чтобы ни один из них не выпал за допуск. Точки, в
// которой «идеально», здесь просто нет.

(() => {
  const L = Rig.rows({
    id: 'd_load',
    board: DB.s.board,
    supply: { id: 'SUP', name: 'Ввод привода', label: '12 В', silk: 'G1', value: 12 },
    rated: 0.35,
    rows: [
      {
        id: 'DR', rated: 0.35,
        items: [
          deckSocket('R1', 'Гнездо балласта', { silk: 'R1', title: 'Что поставить в гнездо', jumper: false, rated: { pMax: 2.5, tau: 1.2 } }),
          { id: 'M1', kind: 'motor', name: 'Привод', silk: 'M1', value: 47, rated: { iNom: 0.28, pMax: 6.0, tau: 2.0 } },
        ],
      },
    ],
  });

  createLevel(LevelRegistry.register({
    id: 'd_load',
    index: 59,
    title: 'Привод под нагрузкой',
    teaches: 'один балласт на два режима',
    silk: 'LOD-022-45',
    diag: 'ДИАГНОСТИКА · Узел Д-05: ток привода выходит за допуск при смене нагрузки.',
    brief: 'Привод работает то вхолостую, то под нагрузкой, и сам меняет режим каждые пару секунд — это видно на ленте. Ток обязан оставаться между 160 и 300 мА в ОБОИХ режимах. Гнездо балласта пустое.',
    lesson: 'Под нагрузкой обмотка привода отдаёт меньше сопротивления, и ток растёт; вхолостую — наоборот. Балласт при этом один. Значит подбирать его надо не под удобный режим, а так, чтобы оба края уложились в допуск: слишком маленький выпустит ток за верхний край под нагрузкой, слишком большой уронит его под нижний на холостом ходу. Настраивать по одной точке здесь бессмысленно — узел проверяется целиком.',
    reveal: 'Привод забортного насоса. Нагрузка менялась потому, что менялось то, что он качал.',
    hints: [
      'Смотри на ленту хотя бы несколько секунд: ток ходит вверх-вниз сам.',
      'Посчитай оба края: 12 вольт делить на сумму балласта с привода, отдельно для 47 и отдельно для 22 ом.',
      'Нужен номинал, при котором и верхний край не выше 300 мА, и нижний не ниже 160.',
    ],
    codex: ['motor', 'ohm', 'current', 'resistor'],
    vmax: 12.0,
    hold: 4.0,
    testSeconds: 6.5,
    scale: DB.s.scale,
    board: DB.s.board,
    map: { pos: vec(538, 265), radius: 900, color: hex(0xff9a3c), from: ['d_pulse', 'd_clamp'], icon: { kind: 'motor' } },
    goalText: 'Ток привода в пределах 160…300 мА в обоих режимах.',
    scope: { label: 'Ток привода', get: (m) => m.i, min: 0, max: 0.45, band: [0.16, 0.30], fmt: fmtAmps },

    parts: L.parts,
    wires: L.wires,
    build: (c, P) => Rig.build(c, P),
    apply: (refs, P, c) => Rig.apply(c, refs, P),

    // Нагрузка привода меняется сама — это и есть проверка узла. Сопротивление
    // обмотки меняем через поле детали; Rig.apply переносит его в цепь
    // методом setResistance, как того требует правило проекта.
    tick(dt, P) {
      P.M1.phase = ((P.M1.phase || 0) + dt) % 4;
      P.M1.value = P.M1.phase < 2 ? 47 : 22;
    },

    read(sol, refs, P) {
      const i = Math.abs(sol.componentCurrent.M1 || 0);
      return {
        i,
        heavy: P.M1.value <= 30,
        empty: !P.R1.content,
        ok: i >= 0.16 && i <= 0.30,
      };
    },

    status(m) {
      if (m.empty) return ['Гнездо балласта пустое — привод стоит.', 'neutral'];
      if (m.ok) return ['Ток держится в допуске и под нагрузкой, и вхолостую.', 'good'];
      if (m.i > 0.30) return ['Под нагрузкой ток выскочил за 300 мА: балласт мал.', 'warn'];
      return ['Вхолостую ток провалился ниже 160 мА: балласт велик.', 'warn'];
    },

    goal(m) {
      if (m.empty) return { ok: false, note: 'Балласт не поставлен.' };
      return {
        ok: m.ok,
        note: 'Сейчас ' + fmtAmps(m.i) + ' (' + (m.heavy ? 'под нагрузкой' : 'холостой ход') + '), допуск 160…300 мА',
      };
    },

    score(m) { return m.ok ? bandScore(m.i, 0.23, 0.30) : 0; },
    scoreNote(m) { return 'Ток держится в допуске на обоих режимах — от ' + fmtAmps(0.173) + ' до ' + fmtAmps(0.270); },

    meter(m) {
      return [
        ['Ток привода', fmtAmps(m.i), m.ok ? 'good' : 'warn'],
        ['Режим', m.heavy ? 'под нагрузкой' : 'холостой ход'],
        ['Нижний предел', '160 мА'],
        ['Верхний предел', '300 мА'],
      ];
    },
  }));
})();
