'use strict';
// Х-01 · Узел, которого нет ни в одной описи.
//
// Он не открывается прохождением соседа: на карте его вообще нет, пока игрок
// не снял все шесть неучтённых токов (SECRET_TAPS в _deck.js). Шесть отводов
// уходили с шести разных плат в одну точку — сюда. Здесь их надо собрать
// обратно: каждая ветка обязана взять ровно тот ток, который уходил мимо
// схемы на своей плате.
//
// Задача при этом не спрятана ни на грамм: рядом с каждым гнездом написано,
// сколько миллиампер оно должно взять. Спрятано было другое — сам факт, что
// эти шесть чисел существуют и складываются во что-то.

(() => {
  const BOARD = { x: -350, y: -250, w: 700, h: 500 };

  // Гнёзда: у каждого три номинала на выбор. Ошибиться можно, угадать все
  // шесть подряд — нет.
  function tapSocket(id, tap, kit) {
    const t = SECRET_TAPS[tap - 1];
    return {
      id, kind: 'socket', name: 'Отвод ' + tap + ' · нужно ' + Math.round(12000 / t.ohms) + ' мА',
      silk: 'R' + tap, showValue: true, valueText: socketLabel, content: null,
      rated: { pMax: 2.0, tau: 1.0 },
      interact: {
        type: 'pick', title: 'Отвод ' + tap + ': нужно ' + fmtAmps(12 / t.ohms),
        hint: 'Нажми, чтобы выбрать номинал',
        // Пункта «пусто» здесь нет нарочно: гнёзда и так пустые с самого
        // начала, а шесть вариантов «убрать обратно» только раздувают перебор
        // и ничего игроку не дают.
        options: () => kit.map((r) => ({ label: fmtOhms(r), content: { kind: 'resistor', value: r } })),
      },
    };
  }

  const KITS = [
    [1000, 2200, 4700],
    [1000, 2200, 4700],
    [470, 1000, 2200],
    [100, 220, 470],
    [220, 470, 1000],
    [100, 150, 220],
  ];

  const L = Rig.rows({
    id: 'x_logger',
    board: BOARD,
    supply: { id: 'SUP', name: 'Ввод узла', label: '12 В', silk: 'G1', value: 12 },
    rated: 0.1,
    rows: KITS.map((kit, k) => ({
      id: 'TP' + (k + 1), rated: 0.1,
      items: [tapSocket('R' + (k + 1), k + 1, kit)],
    })),
  });

  const TARGETS = SECRET_TAPS.map((t) => 12 / t.ohms);

  createLevel(LevelRegistry.register({
    id: 'x_logger',
    index: 77,
    title: 'Регистратор',
    teaches: 'шесть измерений, сведённые обратно',
    silk: 'XXX-000-77',
    diag: 'ДИАГНОСТИКА · Узел не числится в описи. Обозначение присвоено ремонтной подсистемой.',
    brief: 'Шесть отводов, которые ты нашёл по неучтённому току на шести платах, сходятся здесь. Все шесть гнёзд пустые, и узел мёртв. Рядом с каждым гнездом написано, какой ток по нему шёл — восстанови каждое так, чтобы ток совпал.',
    lesson: 'Ничего нового в этом узле нет: шесть раз закон Ома, каждый со своим числом. Всё, чем он отличается от остальных, — числа взяты не из паспорта, а сняты приборами по всей плате. Так и работает диагностика: сумма токов на вводе всегда должна сходиться с суммой того, что берут ветки, и если не сходится — где-то есть ветка, которой нет на схеме.',
    reveal: 'Автономный регистратор. Он не значится в описи, потому что его собрали здесь, на месте, из того, что было: питания ему не выделили, и он брал по нескольку миллиампер с каждой шины, чтобы никто этого не заметил. Всё это время он писал. Последняя запись сделана рукой, а не прибором: «Резерва на одного хватит на дольше, чем на четверых. Уходят они, остаюсь я. Ремонтную подсистему поднимет тот, кто придёт. Если ты это читаешь — значит, кто-то пришёл».',
    hints: [
      'Токи каждого отвода записаны в журнале изделия — там же, где ты их и снял.',
      'Номинал считается из напряжения и тока: двенадцать вольт делить на нужный ток.',
      'Начни с самого крупного тока — ему соответствует самый маленький номинал.',
    ],
    codex: ['ohm', 'current', 'resistor', 'circuit'],
    vmax: 12.0,
    hold: 3.0,
    scale: 1.05,
    board: BOARD,
    map: {
      pos: vec(0, 1345), radius: 900, color: hex(0xd0a8ff),
      needs: SECRET_TAPS.map((t) => t.id),
      icon: { kind: 'resistor', value: 470 },
    },
    goalText: 'Все шесть отводов должны взять свой ток (допуск ±6%).',
    scope: { label: 'Совпало отводов', get: (m) => m.hits, min: 0, max: 6, band: [6, 6], fmt: (v) => Math.round(v) + ' из 6' },

    parts: L.parts,
    wires: L.wires,
    build: (c, P) => Rig.build(c, P),
    apply: (refs, P, c) => Rig.apply(c, refs, P),

    read(sol, refs, P) {
      const cur = [];
      const okk = [];
      let hits = 0;
      for (let k = 0; k < 6; k++) {
        const i = Math.abs(sol.componentCurrent['R' + (k + 1)] || 0);
        const filled = !!P['R' + (k + 1)].content;
        const good = filled && inPct(i, TARGETS[k], 0.06);
        cur.push(filled ? i : NaN);
        okk.push(good);
        if (good) hits += 1;
      }
      return {
        cur, okk, hits,
        total: cur.reduce((a, b) => a + (isFinite(b) ? b : 0), 0),
        ok: hits === 6,
      };
    },

    status(m) {
      if (m.ok) return ['Все шесть отводов сведены. Узел под питанием и отвечает.', 'good'];
      if (m.hits === 0) return ['Ни один отвод пока не совпал. Токи записаны в журнале.', 'neutral'];
      return ['Совпало ' + m.hits + ' из шести. Остальные ещё не на своих номиналах.', 'warn'];
    },

    goal(m) {
      return { ok: m.ok, note: 'Совпало ' + m.hits + ' отводов из шести' };
    },

    score(m) { return m.ok ? 1 : 0; },
    scoreNote(m) { return 'Шесть отводов дают вместе ' + fmtAmps(m.total) + ' — ровно то, чего не хватало в шести бюджетах'; },

    meter(m) {
      const rows = [];
      for (let k = 0; k < 6; k++) {
        rows.push(['Отвод ' + (k + 1) + ' · нужно ' + fmtAmps(TARGETS[k]),
          isFinite(m.cur[k]) ? fmtAmps(m.cur[k]) : '—',
          m.okk[k] ? 'good' : 'warn']);
      }
      rows.push(['Совпало', m.hits + ' из 6', m.ok ? 'good' : '']);
      return rows;
    },
  }));
})();
