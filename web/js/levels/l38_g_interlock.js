'use strict';
// Г-05 · Пусковой реостат. Порядок действий здесь важнее номиналов: сначала
// пустить через сопротивление, и только когда привод пошёл — обойти его.
// Сделать наоборот можно, и уровень это честно засчитает как неудачу.

(() => {
  const L = Rig.rows({
    id: 'g_interlock',
    board: DB.l.board,
    busX: { MOT: 0.5 },
    supply: { id: 'SUP', name: 'Ввод привода', label: '12 В', silk: 'G1', value: 12 },
    rated: 0.6,
    rows: [
      {
        id: 'ST', to: 'MOT', rated: 0.25,
        items: [
          deckToggle('SA1', 'Ключ пуска', false, 'Нажми, чтобы пустить привод через реостат'),
          deckSocket('RS', 'Гнездо пускового', { silk: 'RS', title: 'Через что пускать', jumper: false, rated: { pMax: 3.0, tau: 1.2 } }),
        ],
      },
      {
        id: 'BP', to: 'MOT', rated: 0.6,
        items: [deckToggle('SA2', 'Обход реостата', false, 'Нажми, чтобы закоротить пусковой реостат')],
      },
      {
        id: 'DR', from: 'MOT', rated: 0.6,
        items: [{ id: 'M1', kind: 'motor', name: 'Тяжёлый привод', silk: 'M1', value: 20, rated: { iNom: 0.55, pMax: 14.0, tau: 2.0 } }],
      },
    ],
  });

  createLevel(LevelRegistry.register({
    id: 'g_interlock',
    index: 52,
    title: 'Пусковой реостат',
    teaches: 'пуск под сопротивлением',
    silk: 'ILK-033-38',
    diag: 'ДИАГНОСТИКА · Узел Г-05: привод пускают напрямую, пусковой ток вне нормы.',
    brief: 'Тяжёлый привод в рабочем режиме берёт больше половины ампера, и это нормально. Ненормально другое: паспорт запрещает трогать его с места током больше 250 мА и меньше 150 мА. Пустить надо через реостат, а потом обойти его.',
    lesson: 'Сопротивление самого привода мало, и включённый напрямую он в первый момент берёт весь ток, который может дать шина. Поэтому тяжёлое пускают через добавочное сопротивление: оно ограничивает рывок. Как только привод пошёл, реостат закорачивают — иначе он будет вечно греться и отбирать у привода рабочее напряжение. Порядок здесь важнее номиналов.',
    reveal: 'Привод главного люка. Реостат обойдён и оставлен в обходе — люк открывали в последний раз в спешке.',
    hints: [
      'Замкни только ключ пуска и посмотри, какой ток пошёл через привод.',
      'Пусковой ток — это двенадцать вольт делить на сумму реостата и самого привода. Привод даёт двадцать ом.',
      'Когда пуск уложился в норму, замкни обход: реостат закоротится и привод выйдет на рабочий ток.',
    ],
    codex: ['motor', 'ohm', 'resistor', 'switch', 'power'],
    vmax: 12.0,
    hold: 2.0,
    // Победа здесь — ПОРЯДОК действий во времени (пустить через реостат,
    // потом обойти его), а не положение деталей: перебор состояний её не
    // найдёт. Проверено отдельным прогоном последовательности: реостат 33
    // или 47 Ом даёт пуск 225 и 178 мА и рабочий ток 588 мА.
    sequenced: true,
    minScore: 0.71,
    scale: DB.l.scale,
    board: DB.l.board,
    map: { pos: vec(-967, 415), radius: 900, color: hex(0xff9a3c), from: ['g_delay', 'g_latch'], icon: { kind: 'motor' } },
    goalText: 'Пуск 150…250 мА, потом рабочий ток не ниже 500 мА.',
    scope: { label: 'Ток привода', get: (m) => m.i, min: 0, max: 0.8, band: [0.5, 0.8], fmt: fmtAmps },

    parts: L.parts,
    wires: L.wires,
    build: (c, P) => Rig.build(c, P),
    apply: (refs, P, c) => Rig.apply(c, refs, P),

    // Пусковой ток — это ток, пока обход РАЗОМКНУТ. После замыкания обхода
    // ток честно вырастает до рабочего, и общий пик тут ничего не сказал бы:
    // считать надо только фазу пуска. Оба ключа разомкнуты — счёт сброшен.
    tick(dt, P, m) {
      if (!P.SA1.closed && !P.SA2.closed) { P.M1.iStart = 0; return; }
      if (!P.SA2.closed) P.M1.iStart = Math.max(P.M1.iStart || 0, Math.abs(m.i));
    },

    read(sol, refs, P) {
      const i = Math.abs(sol.componentCurrent.M1 || 0);
      const iStart = P.M1.iStart || 0;
      return {
        i, iStart,
        bypass: !!P.SA2.closed,
        started: !!P.SA1.closed,
        empty: !P.RS.content,
        startOk: iStart >= 0.15 && iStart <= 0.25,
        runOk: i >= 0.5,
      };
    },

    status(m) {
      if (m.empty && !m.bypass) return ['Гнездо пускового пустое — привод не тронется.', 'neutral'];
      if (m.startOk && m.runOk) return ['Пуск уложился в норму, привод вышел на рабочий ток.', 'good'];
      if (m.iStart > 0.25) return ['Пусковой ток был ' + fmtAmps(m.iStart) + ' — привод дёрнули слишком резко. Разомкни оба ключа и начни заново.', 'bad'];
      if (m.iStart > 0 && m.iStart < 0.15) return ['Пусковой ток всего ' + fmtAmps(m.iStart) + ' — привод не стронется, реостат слишком велик.', 'warn'];
      if (!m.started) return ['Оба ключа разомкнуты. Пускай ключом пуска, обход — потом.', 'neutral'];
      if (!m.bypass) return ['Пуск идёт нормально. Теперь замкни обход, чтобы привод вышел на рабочий ток.', 'warn'];
      return ['Привод под током, но рабочего режима нет.', 'warn'];
    },

    goal(m) {
      if (!m.startOk) {
        return {
          ok: false,
          note: m.iStart > 0 ? 'Пуск был ' + fmtAmps(m.iStart) + ', нужно 150…250 мА' : 'Пуска ещё не было.',
        };
      }
      return { ok: m.runOk, note: 'Рабочий ток ' + fmtAmps(m.i) + ', нужно не ниже 500 мА' };
    },

    score(m) { return (m.startOk && m.runOk) ? clamp(0.6 + (m.i - 0.5) * 1.2, 0.6, 1) : 0; },
    scoreNote(m) { return 'Пуск ' + fmtAmps(m.iStart) + ', рабочий ток ' + fmtAmps(m.i) + ' — разница почти втрое'; },

    meter(m) {
      return [
        ['Пусковой ток', m.iStart > 0 ? fmtAmps(m.iStart) : '—', m.startOk ? 'good' : (m.iStart > 0 ? 'bad' : '')],
        ['Ток сейчас', fmtAmps(m.i), m.runOk ? 'good' : ''],
        ['Обход', m.bypass ? 'замкнут' : 'разомкнут'],
        ['Пуск разрешён', '150…250 мА'],
        ['Рабочий', 'не ниже 500 мА'],
      ];
    },
  }));
})();
