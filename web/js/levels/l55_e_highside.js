'use strict';
// Е-08 · Где рвать цепь. Единственный узел, где задача — не включить, а
// ВЫКЛЮЧИТЬ, причём выключить правильно. Ток гаснет одинаково при любом из
// двух разрывов, а вот корпус остаётся под напряжением только при одном.

(() => {
  const L = Rig.rows({
    // Петля одна, а значок нужен: урок про разницу между разрывом в плюсе и в земле.
    groundSymbol: true,
    id: 'e_highside',
    board: DB.m.board,
    supply: { id: 'SUP', name: 'Ввод узла', label: '12 В', silk: 'G1', value: 12 },
    rated: 0.25,
    rows: [
      {
        id: 'LD', rated: 0.25,
        items: [
          deckToggle('SA1', 'Ключ в плюсовом проводе', true, 'Нажми, чтобы замкнуть или разомкнуть'),
          { id: 'HL1', kind: 'lamp', name: 'Корпусный светильник', silk: 'HL1', value: 68, showValue: true, rated: { pNom: 1.9, pMax: 5.0, tau: 1.2 } },
          deckToggle('SA2', 'Ключ в обратном проводе', true, 'Нажми, чтобы замкнуть или разомкнуть'),
        ],
      },
    ],
  });

  createLevel(LevelRegistry.register({
    id: 'e_highside',
    index: 69,
    title: 'Где рвать цепь',
    teaches: 'разрыв в плюсе и разрыв в земле — не одно и то же',
    silk: 'HSD-000-69',
    diag: 'ДИАГНОСТИКА · Узел Е-08: светильник под напряжением, к нему нельзя подойти.',
    brief: 'Светильник надо обесточить, чтобы до него можно было дотронуться. Ключей два: один стоит в плюсовом проводе до светильника, второй — в обратном, после него. Нужно, чтобы ток погас И на корпусе светильника не осталось напряжения.',
    lesson: 'Ток гаснет от разрыва в любом месте кольца — это правда, и в этом смысле оба ключа одинаковы. Но потенциал остаётся там, куда он дотянулся. Разорви обратный провод — и корпус светильника через саму нагрузку по-прежнему связан с плюсом, то есть на нём остаются все двенадцать вольт, хотя не горит ничего. Разорви плюсовой — и корпус остаётся связан с землёй, то есть на нём честный ноль. Поэтому выключатель ставят в плюсовой провод, а не в обратный: разница видна не по лампе, а по руке.',
    reveal: 'Светильник у переходного люка. Оба ключа найдены замкнутыми: последний, кто здесь был, ушёл, не выключив свет.',
    hints: [
      'Разомкни сначала один ключ, потом другой, и следи не за током, а за строкой «На корпусе».',
      'Разомкнутый обратный провод оставляет корпус связанным с плюсом через саму лампу.',
      'Оба ключа разом тоже не годятся: корпус повисает ни на чём, и напряжение на нём становится неопределённым.',
    ],
    codex: ['switch', 'ground', 'circuit', 'current'],
    vmax: 12.0,
    hold: 2.0,
    scale: DB.m.scale,
    board: DB.m.board,
    map: { pos: vec(0, 795), radius: 900, color: hex(0x6ee7a8), from: ['e_bleed', 'e_eff'], icon: { kind: 'toggle' } },
    goalText: 'Ток погашен и на корпусе светильника меньше 1 В.',
    scope: { label: 'Напряжение на корпусе', get: (m) => m.uCase, min: 0, max: 12, band: [0, 1], fmt: fmtVolts },

    parts: L.parts,
    wires: L.wires,
    build: (c, P) => Rig.build(c, P),
    apply: (refs, P, c) => Rig.apply(c, refs, P),

    read(sol, refs, P) {
      const i = Math.abs(sol.componentCurrent.HL1 || 0);
      const uCase = sol.nodeVoltage.LD_2 || 0;
      return {
        i, uCase,
        top: !!P.SA1.closed,
        bot: !!P.SA2.closed,
        both: !P.SA1.closed && !P.SA2.closed,
        ok: i < 0.005 && uCase < 1.0 && (!!P.SA2.closed),
      };
    },

    status(m) {
      if (m.ok) return ['Разорван плюсовой провод: тока нет, корпус сидит на земле. Так и надо.', 'good'];
      if (m.both) return ['Оба ключа разомкнуты — корпус повис ни на чём, и напряжение на нём не определено. Так тоже нельзя.', 'bad'];
      if (m.top && !m.bot) return ['Разорван обратный провод. Лампа не горит, а на корпусе остались все двенадцать вольт.', 'bad'];
      if (m.top && m.bot) return ['Оба ключа замкнуты, светильник горит — обесточить не получилось.', 'neutral'];
      return ['Почти: тока нет, но напряжение с корпуса ещё не ушло.', 'warn'];
    },

    goal(m) {
      if (m.i >= 0.005) return { ok: false, note: 'Светильник ещё горит: ток ' + fmtAmps(m.i) };
      return { ok: m.ok, note: 'На корпусе ' + fmtVolts(m.uCase) + ', разрешено меньше 1 В' };
    },

    score(m) { return m.ok ? 1 : 0; },
    scoreNote(m) { return 'Тока нет, на корпусе ' + fmtVolts(m.uCase) + ' — к светильнику можно подходить'; },

    meter(m) {
      return [
        ['Ток светильника', fmtAmps(m.i), m.i < 0.005 ? 'good' : 'warn'],
        ['На корпусе', fmtVolts(m.uCase), m.uCase < 1 ? 'good' : 'bad'],
        ['Плюсовой ключ', m.top ? 'замкнут' : 'разомкнут'],
        ['Обратный ключ', m.bot ? 'замкнут' : 'разомкнут'],
        ['Нужно', 'ноль тока и ноль на корпусе'],
      ];
    },
  }));
})();
