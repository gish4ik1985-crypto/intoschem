'use strict';
// Уровень 15 · Силовой ключ.
// Вторая половина транзистора, которой не было в уровне 13: насыщение.
// Там транзистор работал усилителем и до полки не доходил; здесь он
// работает ключом, и вся суть — загнать его в полку и не задержаться по
// дороге. Полуоткрытый транзистор — не «промежуточный режим», а место,
// где он греется сильнее всего и умирает.

const Level15 = createLevel(LevelRegistry.register({
  id: 'saturation',
  index: 29,
  title: 'Силовой ключ',
  teaches: 'насыщение',
  silk: 'SW-SAT-15',
  diag: 'ДИАГНОСТИКА · Силовой ключ прожектора открыт лишь на малую часть хода.',
  brief: 'Прожектор еле тлеет: транзистор приоткрыт совсем чуть-чуть. Открывай ручкой — но не задерживайся посередине: приоткрытый транзистор греется сильнее всего и успевает сгореть.',
  lesson: 'Транзистор как ключ бывает в двух хороших положениях. Закрыт — тока нет, греться нечему. Открыт до конца — ток идёт, но на самом транзисторе почти ничего не падает, и греться опять нечему. А приоткрытый — худшее место: через него уже течёт большой ток, и на нём ещё висит большое напряжение, а тепло это их произведение. И сколько ни увеличивай ток базы дальше, ток нагрузки не вырастет: заслонка не может открыться шире трубы, дальше ограничивает уже сама нагрузка. Это и называется насыщением.',
  hints: [
    'Смотри на ленту снизу: это мощность, которая выделяется на самом транзисторе. Она не растёт монотонно — у неё горб.',
    'Открывай дальше горба. За ним напряжение на транзисторе падает почти до нуля, и он перестаёт греться.',
    'После насыщения ток лампы перестаёт расти совсем. Значит, дальше крутить смысла нет — только зря тратить ток базы.',
  ],
  codex: ['transistor', 'power', 'ohm', 'lamp'],
  vmax: 12.0,
  hold: 3.0,
  scale: 1.22,
  board: { x: -300, y: -150, w: 600, h: 300 },
  map: { pos: vec(-1397, -135), radius: 900, color: hex(0xffd166), from: ['fork', 'sensor'], icon: { kind: 'transistor' } },
  goalText: 'Прожектор в полную силу, транзистор холодный, ток базы не больше 30 мА.',
  scope: { label: 'Мощность на транзисторе', get: (m) => m.pT, min: 0, max: 1.3, band: [0, 0.12], fmt: fmtWatts },

  parts: [
    { id: 'SUP', kind: 'supply', pos: vec(-236, -70), name: 'Питание прожектора', label: '12 В', silk: 'G1', nets: ['VCC', 'GND'], comp: 'V1' },
    {
      id: 'LAMP', kind: 'lamp', pos: vec(-30, -100), name: 'Прожектор', silk: 'HL1',
      nets: ['VCC', 'COLL'], comp: 'LAMP', rated: { pNom: 4.6, pMax: 9.0, tau: 0.8 },
    },
    {
      // y=-20, а не -30: при -30 зона клика ручки (86×86) на пару пикселей
      // задевала соседний прожектор — с прожектором клик не делает ничего,
      // но иногда «съедал» попытку крутить ручку у самого края.
      id: 'POT', kind: 'pot', pos: vec(-110, -20), name: 'Ручка открытия', silk: 'R1',
      nets: ['VCC', 'BASE'], comp: 'RB', value: 35000, knob: 0.05,
      interact: {
        type: 'knob', hint: 'Крути колесом мыши или тяни вверх-вниз',
        // Логарифмическая шкала: у линейной вся интересная часть
        // сминалась бы в последние проценты хода ручки.
        map: (k) => Math.round(Math.exp(lerp(Math.log(47000), Math.log(150), clamp(k, 0, 1)))),
      },
    },
    {
      id: 'T1', kind: 'transistor', pos: vec(140, -40), name: 'Силовой транзистор n-p-n', silk: 'VT1',
      // Меряем именно коллектор-эмиттер: это то напряжение, которое
      // остаётся на самом транзисторе, и вместе с током даёт его нагрев.
      nets: ['COLL', 'GND'], comp: 'T1', rated: { pMax: 0.9, tau: 2.5 },
    },
  ],

  wires: [
    { pts: [vec(-172, -88), vec(-172, -100), vec(-64, -100)], net: 'VCC', via: 'LAMP', rated: 0.4 },
    { pts: [vec(-153, -100), vec(-153, 6)], net: 'VCC', via: 'RB', rated: 0.03 },
    { pts: [vec(4, -100), vec(60, -100), vec(60, 30), vec(140, 30), vec(140, -6)], net: 'COLL', via: 'LAMP', rated: 0.4 },
    { pts: [vec(-67, 6), vec(-67, 66), vec(116, 66), vec(116, -6)], net: 'BASE', via: 'RB', rated: 0.03 },
    { pts: [vec(164, -6), vec(164, 96), vec(-172, 96), vec(-172, -52)], net: 'GND', via: 'LAMP', rated: 0.4 },
  ],

  build(c) {
    addSupply(c, 'VCC', 'GND', 12.0, 'V1', SUPPLY_R.BENCH);
    const lamp = addLamp(c, 'VCC', 'COLL', 30.0, 'LAMP');
    const rb = c.addResistor('VCC', 'BASE', 35000, 'RB');
    c.addTransistor('BASE', 'COLL', 'GND', 'T1');
    return { LAMP: lamp, RB: rb };
  },

  apply(refs, P, c) { c.setResistance(refs.RB, P.POT.value); },

  read(sol, refs, P) {
    return {
      ib: Math.abs(sol.componentCurrent['RB'] || 0),
      ic: Math.abs(sol.componentCurrent['LAMP'] || 0),
      vce: sol.nodeVoltage['COLL'] || 0,
      pT: P.T1.p || 0,
      burnt: P.T1.burnt,
      heat: P.T1.heat || 0,
    };
  },

  status(m) {
    if (m.burnt) return ['Транзистор сгорел — он слишком долго простоял приоткрытым. Замени и проскочи середину быстрее.', 'bad'];
    if (m.ic >= 0.38 && m.ib > 0.03) return ['Открыт до конца, но ток базы великоват: дальше полки он уже ничего не даёт, только тратится зря.', 'warn'];
    if (m.ic >= 0.38) return ['Насыщение: на транзисторе почти ноль вольт, греться нечему, прожектор на полную.', 'good'];
    if (m.heat > 0.55) return ['Транзистор раскаляется! Он приоткрыт — это худшее для него положение. Открывай дальше.', 'bad'];
    if (m.ic > 0.15) return ['Уже светит, но транзистор в самом горячем месте. Не задерживайся здесь.', 'warn'];
    return ['Транзистор почти закрыт, прожектор еле тлеет.', 'neutral'];
  },

  goal(m) {
    if (m.burnt) return { ok: false, note: 'Транзистор сгорел — замени его.' };
    return {
      ok: m.ic >= 0.38 && m.pT <= 0.12 && m.ib <= 0.03,
      note: 'Прожектор ' + fmtAmps(m.ic) + ' · на транзисторе ' + fmtVolts(m.vce)
        + ' · база ' + fmtAmps(m.ib),
    };
  },

  score(m) { return m.burnt ? 0 : clamp(m.ic / 0.39, 0, 1) * (m.pT <= 0.12 ? 1 : 0.55); },
  scoreNote(m) {
    return 'На транзисторе остаётся ' + fmtVolts(m.vce) + ' — он рассеивает ' + fmtWatts(m.pT)
      + ' вместо горба в 1,1 Вт';
  },

  meter(m) {
    return [
      ['Ток базы', fmtAmps(m.ib), m.ib > 0.03 ? 'warn' : 'good'],
      ['Ток прожектора', fmtAmps(m.ic), m.ic >= 0.38 ? 'good' : 'warn'],
      ['На транзисторе', fmtVolts(m.vce), m.vce < 0.3 ? 'good' : 'warn'],
      ['Греется транзистор', fmtWatts(m.pT), m.pT > 0.4 ? 'bad' : (m.pT <= 0.12 ? 'good' : 'warn')],
      ['Нагрев', Math.round(clamp(m.heat, 0, 1) * 100) + '%', m.heat > 0.6 ? 'bad' : ''],
    ];
  },
}));
