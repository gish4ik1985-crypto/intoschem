'use strict';
// Т-08 · Делитель. Первая сборка, где нужен не ток, а НАПРЯЖЕНИЕ в точке.
// Нагрузки к средней точке намеренно не подключено ничего: делитель под
// нагрузкой — отдельный разговор, и он будет позже. Здесь только само
// правило: напряжение делится в тех же долях, что и сопротивления.

(() => {
  const KIT = [100, 220, 470, 1000];
  const L = Rig.rows({
    // Петля одна, а значок нужен: точка меряется ОТНОСИТЕЛЬНО земли — потенциал без опоры не существует.
    groundSymbol: true,
    id: 't_divider',
    board: DB.m.board,
    busX: { MID: 0.5 },
    supply: { id: 'SUP', name: 'Питание стенда', label: '12 В', silk: 'G1', value: 12 },
    rated: 0.1,
    rows: [
      {
        id: 'TOP', to: 'MID', rated: 0.1,
        items: [deckSocket('R1', 'Верхнее плечо', { silk: 'R1', title: 'Верхнее плечо делителя', jumper: false, kit: KIT, rated: { pMax: 2.0, tau: 1.0 } })],
      },
      {
        id: 'BOT', from: 'MID', rated: 0.1,
        items: [deckSocket('R2', 'Нижнее плечо', { silk: 'R2', title: 'Нижнее плечо делителя', jumper: false, kit: KIT, rated: { pMax: 2.0, tau: 1.0 } })],
      },
    ],
  });

  createLevel(LevelRegistry.register({
    id: 't_divider',
    index: 8,
    title: 'Напряжение делится',
    teaches: 'делитель: напряжение в точке',
    silk: 'STD-008',
    diag: 'СТЕНД · Сборка Т-08: оба плеча делителя пустые.',
    brief: 'Два гнезда стоят столбиком между питанием и землёй, а между ними выведена точка. Нужно, чтобы в этой точке было ровно шесть вольт — половина от питания. Оба гнезда пустые.',
    lesson: 'Через два резистора подряд идёт один и тот же ток, а напряжение на каждом получается своё — по закону Ома, пропорционально его сопротивлению. Значит, точка между ними делит двенадцать вольт в том же отношении, в каком стоят два номинала. Ровно половина получается, когда плечи равны, — и не важно, какие именно, важно что одинаковые.',
    reveal: 'Пункт восьмой: «Половину питания я брал вот так, двумя одинаковыми. Точных деталей на станции нет и не было — есть одинаковые, а этого почти всегда достаточно».',
    hints: [
      'Поставь в оба гнезда что угодно и посмотри, куда сдвинулась точка.',
      'Чем больше верхнее плечо по сравнению с нижним, тем ниже напряжение в точке.',
      'Половина получается ровно тогда, когда оба плеча одинаковые.',
    ],
    codex: ['divider', 'series', 'ohm', 'resistor'],
    vmax: 12.0,
    hold: 2.0,
    scale: DB.m.scale,
    board: DB.m.board,
    map: { pos: vec(0, -1085), radius: 900, color: hex(0xd0a8ff), from: ['t_ground', 't_parallel'], icon: { kind: 'resistor', value: 220 } },
    goalText: 'В средней точке — 6 В (допуск ±5%).',
    scope: { label: 'Напряжение средней точки', get: (m) => m.u, min: 0, max: 12, band: [5.7, 6.3], fmt: fmtVolts },

    parts: L.parts,
    wires: L.wires,
    build: (c, P) => Rig.build(c, P),
    apply: (refs, P, c) => Rig.apply(c, refs, P),

    read(sol, refs, P) {
      const filled = !!P.R1.content && !!P.R2.content;
      // Пока хотя бы одно плечо пустое, напряжение в точке — не показание, а
      // утечка расчёта: делителя физически нет, и показывать там число значит
      // врать прибором. Пустое гнездо честнее показать прочерком.
      return {
        filled,
        u: filled ? (sol.nodeVoltage.MID || 0) : NaN,
        i: Math.abs(sol.componentCurrent.R1 || 0),
        r1: P.R1.content ? P.R1.content.value : 0,
        r2: P.R2.content ? P.R2.content.value : 0,
        ok: filled && inPct(sol.nodeVoltage.MID || 0, 6, 0.05),
      };
    },

    status(m) {
      if (!m.filled) return ['Делителя ещё нет: оба плеча должны быть заняты.', 'neutral'];
      if (m.ok) return ['Шесть вольт. Плечи равны, и точка встала ровно посередине.', 'good'];
      if (m.u > 6.3) return ['Точка стоит высоко: нижнее плечо больше верхнего.', 'warn'];
      return ['Точка стоит низко: верхнее плечо больше нижнего.', 'warn'];
    },

    goal(m) {
      if (!m.filled) return { ok: false, note: 'Оба плеча должны быть заняты.' };
      return { ok: m.ok, note: 'В точке ' + fmtVolts(m.u) + ', нужно 6 В' };
    },

    score(m) { return m.filled ? bandScore(m.u, 6, 0.05) : 0; },
    scoreNote(m) { return 'Плечи ' + fmtOhms(m.r1) + ' и ' + fmtOhms(m.r2) + ', в точке ' + fmtVolts(m.u); },

    meter(m) {
      return [
        ['В средней точке', m.filled ? fmtVolts(m.u) : '—', m.ok ? 'good' : 'warn'],
        ['Верхнее плечо', m.r1 ? fmtOhms(m.r1) : 'пусто'],
        ['Нижнее плечо', m.r2 ? fmtOhms(m.r2) : 'пусто'],
        ['Ток делителя', m.filled ? fmtAmps(m.i) : '—'],
        ['Нужно', '6,0 В'],
      ];
    },
  }));
})();
