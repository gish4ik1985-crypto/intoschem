'use strict';
// Г-07 · Итог сектора. Здесь «и» и «или» стоят в одной схеме одновременно, и
// прочитать её можно только глядя, где ветки идут друг за другом, а где рядом.

(() => {
  const L = Rig.rows({
    id: 'g_soft',
    board: DB.l.board,
    busX: { N1: 0.24 },
    supply: { id: 'SUP', name: 'Ввод управления', label: '12 В', silk: 'G1', value: 12 },
    rated: 0.25,
    rows: [
      {
        id: 'K', to: 'N1', rated: 0.25,
        items: [deckToggle('SA2', 'Ключ дистанции', false, 'Нажми, чтобы замкнуть или разомкнуть')],
      },
      {
        id: 'B', to: 'N1', rated: 0.25,
        items: [{
          id: 'SB1', kind: 'button', name: 'Кнопка на месте', silk: 'SB1', closed: false,
          interact: { type: 'press', hint: 'Держи нажатой — замыкает цепь только пока держишь' },
        }],
      },
      {
        id: 'DR', from: 'N1', rated: 0.25,
        items: [
          deckToggle('SA1', 'Общее разрешение', false, 'Нажми, чтобы замкнуть или разомкнуть'),
          deckSocket('R1', 'Гнездо балласта', { silk: 'R1', title: 'Что поставить в гнездо', jumper: false, rated: { pMax: 2.0, tau: 1.0 } }),
          { id: 'M1', kind: 'motor', name: 'Привод', silk: 'M1', value: 47, rated: { iNom: 0.21, pMax: 4.0, tau: 1.5 } },
        ],
      },
    ],
  });

  createLevel(LevelRegistry.register({
    id: 'g_soft',
    index: 54,
    title: 'Разрешение и команда',
    teaches: '«и» и «или» в одной схеме',
    silk: 'SFT-209-40',
    diag: 'ДИАГНОСТИКА · Узел Г-07: привод не отвечает ни на дистанционную команду, ни на местную.',
    brief: 'Привод должен брать 209 мА и работать без человека у платы. Команду можно подать двумя способами — ключом дистанции или кнопкой на месте, — но и то и другое бесполезно без общего разрешения, которое стоит отдельно. Гнездо балласта пустое.',
    lesson: 'Всё, что нужно для чтения такой схемы, — смотреть, где ветки идут ДРУГ ЗА ДРУГОМ, а где РЯДОМ. Друг за другом — это «и»: разорви любую, и тока нет. Рядом — это «или»: достаточно одной. Кнопка тут вторая половина «или», и потому она команда, а не разрешение: держать её никто не станет.',
    reveal: 'Пост управления приводом. Дистанционный ключ разомкнут, кнопка цела, общее разрешение снято. Всё выключено правильно — так выключают, когда уходят надолго.',
    hints: [
      'Нажми кнопку и посмотри, что нужно ещё, чтобы привод пошёл.',
      'Общее разрешение стоит в той же ветке, что и привод, — без него не поможет ни одна команда.',
      'Проверяется узел при отпущенной кнопке: команда должна держаться сама.',
    ],
    codex: ['switch', 'circuit', 'series', 'ohm', 'motor'],
    vmax: 12.0,
    hold: 3.0,
    scale: DB.l.scale,
    board: DB.l.board,
    map: { pos: vec(-537, 415), radius: 900, color: hex(0x2fd4c8), from: ['g_or', 'g_dim'], icon: { kind: 'toggle' } },
    goalText: 'Привод — 209 мА (±8%) при отпущенной кнопке.',
    scope: { label: 'Ток привода', get: (m) => m.i, min: 0, max: 0.4, band: [0.1923, 0.2257], fmt: fmtAmps },

    parts: L.parts,
    wires: L.wires,
    build: (c, P) => Rig.build(c, P),
    apply: (refs, P, c) => Rig.apply(c, refs, P),

    read(sol, refs, P) {
      const i = Math.abs(sol.componentCurrent.M1 || 0);
      return {
        i,
        held: !!P.SB1.closed,
        remote: !!P.SA2.closed,
        allow: !!P.SA1.closed,
        empty: !P.R1.content,
        inBand: inPct(i, 0.209, 0.08),
        ok: !P.SB1.closed && inPct(i, 0.209, 0.08),
      };
    },

    status(m) {
      if (m.ok) return ['Разрешение дано, команда держится сама, привод в паспортном режиме.', 'good'];
      if (m.held) return ['Держишь кнопку. Узел должен работать и без неё — отпусти и посмотри.', 'warn'];
      if (!m.allow) return ['Общее разрешение снято: команда есть, а тока нет.', 'warn'];
      if (!m.remote) return ['Разрешение есть, а команды нет: ключ дистанции разомкнут, кнопка отпущена.', 'warn'];
      if (m.empty) return ['Гнездо балласта пустое — кольцо разорвано.', 'neutral'];
      if (m.i > 0.226) return ['Ток великоват: балласт слишком мал.', 'warn'];
      return ['Ток маловат: балласт слишком велик.', 'warn'];
    },

    goal(m) {
      if (m.held) return { ok: false, note: 'Кнопка нажата — так узел не проверяется.' };
      return { ok: m.inBand, note: 'Привод берёт ' + fmtAmps(m.i) + ', нужно 209 мА' };
    },

    score(m) { return m.held ? 0 : bandScore(m.i, 0.209, 0.08); },
    scoreNote(m) { return 'Привод берёт ' + fmtAmps(m.i) + ' по дистанционной команде, без человека у платы'; },

    meter(m) {
      return [
        ['Ток привода', fmtAmps(m.i), m.inBand ? 'good' : 'warn'],
        ['Общее разрешение', m.allow ? 'дано' : 'снято', m.allow ? 'good' : 'warn'],
        ['Ключ дистанции', m.remote ? 'замкнут' : 'разомкнут', m.remote ? 'good' : ''],
        ['Кнопка', m.held ? 'нажата' : 'отпущена', m.held ? 'warn' : 'good'],
        ['Нужно', '209 мА без кнопки'],
      ];
    },
  }));
})();
