'use strict';
// Г-03 · Кнопка и фиксатор. Разница между ними механическая, а не
// электрическая — но в схеме она решает всё: кнопка держит цепь, пока её
// держат, ключ держит её сам.

(() => {
  const L = Rig.rows({
    id: 'g_latch',
    board: DB.l.board,
    busX: { CTL: 0.42 },
    supply: { id: 'SUP', name: 'Ввод управления', label: '12 В', silk: 'G1', value: 12 },
    rated: 0.25,
    rows: [
      {
        id: 'BT', to: 'CTL', rated: 0.25,
        items: [{
          id: 'SB1', kind: 'button', name: 'Кнопка пуска', silk: 'SB1', closed: false,
          interact: { type: 'press', hint: 'Держи нажатой — цепь замкнута только пока держишь' },
        }],
      },
      {
        id: 'LT', to: 'CTL', rated: 0.25,
        items: [deckToggle('SA1', 'Фиксатор пуска', false, 'Нажми, чтобы защёлкнуть или отпустить фиксатор')],
      },
      {
        id: 'DR', from: 'CTL', rated: 0.25,
        items: [
          deckSocket('R1', 'Гнездо балласта', { silk: 'R1', title: 'Что поставить в гнездо', jumper: false, rated: { pMax: 2.0, tau: 1.0 } }),
          { id: 'M1', kind: 'motor', name: 'Привод', silk: 'M1', value: 47, rated: { iNom: 0.21, pMax: 4.0, tau: 1.5 } },
        ],
      },
    ],
  });

  createLevel(LevelRegistry.register({
    id: 'g_latch',
    index: 50,
    title: 'Кнопка и фиксатор',
    teaches: 'кнопка не держит цепь сама',
    silk: 'LCH-209-36',
    diag: 'ДИАГНОСТИКА · Узел Г-03: привод работает только пока держат кнопку.',
    brief: 'Привод должен брать 209 мА и работать САМ, без человека рядом. Кнопка пуска и фиксатор включены рядом; кнопка исправна, фиксатор отпущен, гнездо балласта пустое.',
    lesson: 'Кнопка и ключ электрически — одно и то же: замкнутый контакт. Разница механическая: кнопку пружина возвращает обратно, ключ остаётся там, куда его поставили. Поэтому кнопкой запускают, а держит цепь то, что стоит рядом с ней и умеет оставаться замкнутым. Проверять такой узел надо с ОТПУЩЕННОЙ кнопкой — иначе проверяешь не схему, а свой палец.',
    reveal: 'Пуск вытяжки. Фиксатор отпущен, кнопка цела — значит вытяжку в последний раз включали рукой и держали, пока она работала.',
    hints: [
      'Нажми кнопку и подержи: привод пойдёт. Отпусти — встанет.',
      'Кнопка и фиксатор включены рядом: достаточно любого из них, чтобы цепь была замкнута.',
      'Узел считается исправным только при отпущенной кнопке. Балласт при этом всё равно нужен: привод даёт 47 Ом, а всей ветке нужно около 57.',
    ],
    codex: ['switch', 'circuit', 'ohm', 'motor'],
    vmax: 12.0,
    hold: 3.0,
    scale: DB.l.scale,
    board: DB.l.board,
    map: { pos: vec(-752, 250), radius: 900, color: hex(0xffd166), from: ['g_or', 'b_split'], icon: { kind: 'button' } },
    goalText: 'Привод — 209 мА (±8%) при ОТПУЩЕННОЙ кнопке.',
    scope: { label: 'Ток привода', get: (m) => m.i, min: 0, max: 0.4, band: [0.1923, 0.2257], fmt: fmtAmps },

    parts: L.parts,
    wires: L.wires,
    build: (c, P) => Rig.build(c, P),
    apply: (refs, P, c) => Rig.apply(c, refs, P),

    read(sol, refs, P) {
      const i = Math.abs(sol.componentCurrent.M1 || 0);
      return {
        i,
        held: !!P.SB1.closed,
        latched: !!P.SA1.closed,
        empty: !P.R1.content,
        inBand: inPct(i, 0.209, 0.08),
        ok: !P.SB1.closed && inPct(i, 0.209, 0.08),
      };
    },

    status(m) {
      if (m.ok) return ['Привод держится сам, без кнопки. Узел исправен.', 'good'];
      if (m.held && m.inBand) return ['Ток правильный, но держит его твой палец. Отпусти кнопку — узел должен работать сам.', 'warn'];
      if (m.empty) return ['Гнездо балласта пустое — привод не пойдёт ни от кнопки, ни от фиксатора.', 'neutral'];
      if (m.i < 0.01) return ['Тока нет: ни кнопка не нажата, ни фиксатор не защёлкнут.', 'neutral'];
      if (m.i > 0.226) return ['Ток великоват: балласт слишком мал.', 'warn'];
      return ['Ток маловат: балласт слишком велик.', 'warn'];
    },

    goal(m) {
      if (m.held) return { ok: false, note: 'Кнопка нажата — так узел не проверяется.' };
      return { ok: m.inBand, note: 'Привод берёт ' + fmtAmps(m.i) + ', нужно 209 мА без кнопки' };
    },

    score(m) { return m.held ? 0 : bandScore(m.i, 0.209, 0.08); },
    scoreNote(m) { return 'Привод берёт ' + fmtAmps(m.i) + ' и держится фиксатором, а не рукой'; },

    meter(m) {
      return [
        ['Ток привода', fmtAmps(m.i), m.inBand ? 'good' : 'warn'],
        ['Кнопка', m.held ? 'нажата' : 'отпущена', m.held ? 'warn' : 'good'],
        ['Фиксатор', m.latched ? 'защёлкнут' : 'отпущен', m.latched ? 'good' : ''],
        ['Нужно', '209 мА без кнопки'],
      ];
    },
  }));
})();
