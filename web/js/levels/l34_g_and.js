'use strict';
// Г-01 · Два ключа подряд. Простейшая логика, какая бывает в железе: ток идёт
// только когда замкнуты оба. Никакой отдельной «логики» для этого не нужно —
// достаточно того, что ток течёт по кругу и разрыв в любом месте его гасит.

(() => {
  const L = Rig.rows({
    id: 'g_and',
    board: DB.l.board,
    busX: { CTL: 0.5 },
    supply: { id: 'SUP', name: 'Ввод управления', label: '12 В', silk: 'G1', value: 12 },
    rated: 0.25,
    rows: [
      {
        id: 'SW', to: 'CTL', rated: 0.25,
        items: [
          deckToggle('SA1', 'Разрешение поста', false, 'Нажми, чтобы замкнуть или разомкнуть'),
          deckToggle('SA2', 'Разрешение пульта', false, 'Нажми, чтобы замкнуть или разомкнуть'),
        ],
      },
      {
        id: 'DR', from: 'CTL', rated: 0.25,
        items: [
          deckSocket('R1', 'Гнездо балласта', { silk: 'R1', title: 'Что поставить в гнездо', jumper: false, rated: { pMax: 2.0, tau: 1.0 } }),
          { id: 'M1', kind: 'motor', name: 'Привод', silk: 'M1', value: 47, rated: { iNom: 0.21, pMax: 4.0, tau: 1.5 } },
        ],
      },
    ],
  });

  createLevel(LevelRegistry.register({
    id: 'g_and',
    index: 48,
    title: 'Два разрешения',
    teaches: 'последовательные ключи — это «и»',
    silk: 'AND-209-34',
    diag: 'ДИАГНОСТИКА · Узел Г-01: привод не запускается ни от поста, ни от пульта.',
    brief: 'Привод должен брать 209 мА. В цепи управления два ключа, и оба разомкнуты; гнездо балласта пустое. Записка на плате: «поодиночке не пускать».',
    lesson: 'Два ключа подряд в одной ветке — это условие «и»: ток пойдёт только когда замкнуты оба, потому что разрыв в любом месте кольца останавливает ток везде. Никакой отдельной логики для этого не нужно, достаточно самой цепи. Так и делают блокировки: пока хоть одно разрешение не дано, привод не тронется.',
    reveal: 'Пуск наружного привода. Два разрешения — с поста и с пульта — чтобы никто не запустил его, пока снаружи работает человек.',
    hints: [
      'Попробуй замкнуть только один ключ и посмотри на ток.',
      'Ключи стоят друг за другом в одной ветке: разомкнутый ключ — это разрыв кольца.',
      'Привод даёт 47 Ом. Двенадцать вольт делить на 0,209 ампера — это около 57 Ом на всю ветку.',
    ],
    codex: ['switch', 'circuit', 'series', 'ohm', 'motor'],
    vmax: 12.0,
    hold: 2.5,
    scale: DB.l.scale,
    board: DB.l.board,
    map: { pos: vec(-322, 250), radius: 900, color: hex(0x6ee7a8), from: ['b_parallel', 'b_or'], icon: { kind: 'toggle' } },
    goalText: 'Привод должен брать 209 мА (допуск ±8%).',
    scope: { label: 'Ток привода', get: (m) => m.i, min: 0, max: 0.4, band: [0.1923, 0.2257], fmt: fmtAmps },

    parts: L.parts,
    wires: L.wires,
    build: (c, P) => Rig.build(c, P),
    apply: (refs, P, c) => Rig.apply(c, refs, P),

    read(sol, refs, P) {
      const i = Math.abs(sol.componentCurrent.M1 || 0);
      return {
        i,
        sa1: !!P.SA1.closed, sa2: !!P.SA2.closed,
        both: !!P.SA1.closed && !!P.SA2.closed,
        one: (!!P.SA1.closed) !== (!!P.SA2.closed),
        empty: !P.R1.content,
        ok: inPct(i, 0.209, 0.08),
      };
    },

    status(m) {
      if (m.ok) return ['Оба разрешения даны, привод в паспортном режиме.', 'good'];
      if (m.one) return ['Замкнут только один ключ. Второй разрывает кольцо, и тока нет нигде.', 'warn'];
      if (!m.both) return ['Оба ключа разомкнуты — цепь управления разорвана.', 'neutral'];
      if (m.empty) return ['Ключи замкнуты, но гнездо балласта пустое: кольцо всё равно разорвано.', 'neutral'];
      if (m.i > 0.226) return ['Ток великоват: балласт слишком мал.', 'warn'];
      return ['Ток маловат: балласт слишком велик.', 'warn'];
    },

    goal(m) {
      if (!m.both) return { ok: false, note: 'Нужны оба разрешения сразу.' };
      return { ok: m.ok, note: 'Привод берёт ' + fmtAmps(m.i) + ', нужно 209 мА' };
    },

    score(m) { return m.both ? bandScore(m.i, 0.209, 0.08) : 0; },
    scoreNote(m) { return 'Привод берёт ' + fmtAmps(m.i) + ' и трогается только когда замкнуты оба ключа'; },

    meter(m) {
      return [
        ['Ток привода', fmtAmps(m.i), m.ok ? 'good' : 'warn'],
        ['Разрешение поста', m.sa1 ? 'есть' : 'нет', m.sa1 ? 'good' : ''],
        ['Разрешение пульта', m.sa2 ? 'есть' : 'нет', m.sa2 ? 'good' : ''],
        ['Нужно', '209 мА'],
      ];
    },
  }));
})();
