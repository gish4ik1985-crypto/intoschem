'use strict';
// Е-03 · Разрядный резистор. Обратная сторона выдержки времени: там ёмкость
// набиралась, здесь она обязана СБРОСИТЬСЯ. Узел сам включает и выключает
// питание раз в три секунды — иначе разряд пришлось бы ловить руками, а он
// в этом деле и есть весь смысл.

(() => {
  const L = Rig.rows({
    id: 'e_bleed',
    board: DB.l.board,
    busX: { BUS: 0.45 },
    supply: { id: 'SUP', name: 'Ввод накопителя', label: '12 В', silk: 'G1', value: 12 },
    rated: 0.2,
    rows: [
      {
        id: 'IN', to: 'BUS', rated: 0.2,
        items: [{ id: 'SA1', kind: 'toggle', name: 'Ключ ввода (щёлкает сам)', silk: 'SA1', closed: true }],
      },
      {
        id: 'CP', from: 'BUS', rated: 0.2,
        items: [{ id: 'C1', kind: 'capacitor', name: 'Накопитель', silk: 'C1', value: 4700e-6, vMax: 16, label: '4700 мкФ' }],
      },
      {
        id: 'BL', from: 'BUS', rated: 0.1,
        items: [deckSocket('R1', 'Гнездо разрядного', { silk: 'R1', title: 'Через что разряжать', jumper: true, rated: { pMax: 2.0, tau: 1.0 } })],
      },
    ],
  });

  createLevel(LevelRegistry.register({
    id: 'e_bleed',
    index: 64,
    title: 'Разрядный резистор',
    teaches: 'накопитель надо ещё и разрядить',
    silk: 'BLD-220-64',
    diag: 'ДИАГНОСТИКА · Узел Е-03: накопитель держит заряд после снятия питания.',
    brief: 'Ключ ввода щёлкает сам: три секунды питание есть, три секунды его нет. Правило безопасности требует, чтобы после снятия питания накопитель падал ниже одного вольта — но не быстрее двух секунд и не дольше четырёх. Гнездо разрядного пустое, и сейчас он не разряжается вообще.',
    lesson: 'Выключить питание не значит обесточить: конденсатор остаётся заряженным и после того, как всё погасло, и держит своё напряжение сколько угодно долго, если ему некуда его девать. Поэтому рядом с накопителем ставят разрядный резистор — постоянно висящий на нём и медленно его опустошающий. Время разряда задаёт произведение сопротивления на ёмкость: слишком маленький резистор жжёт ток впустую всё время работы, слишком большой не успевает разрядить накопитель к тому моменту, когда до него дотянется рука.',
    reveal: 'Накопитель силового ввода. Разрядного резистора в нём не было изначально — он выкушен, и рядом лежит записка в одно слово: «осторожно». Кто-то знал, что делает, и оставил предупреждение вместо детали.',
    hints: [
      'Смотри на ленту: питание пропадает само, каждые три секунды.',
      'Время разряда — это сопротивление, умноженное на ёмкость. За одно такое время напряжение падает примерно втрое.',
      'До одного вольта из двенадцати уходит примерно два с половиной таких времени. Ёмкость 4700 мкФ — прикинь, какой нужен резистор.',
    ],
    codex: ['capacitor', 'rc', 'resistor', 'ohm', 'short'],
    vmax: 12.0,
    hold: 2.0,
    testSeconds: 11,
    scale: DB.l.scale,
    board: DB.l.board,
    map: { pos: vec(0, 630), radius: 900, color: hex(0x8fd0ff), from: 'e_polarity', icon: { kind: 'capacitor', value: 4700e-6 } },
    goalText: 'После снятия питания накопитель падает ниже 1 В за 2…4 секунды.',
    scope: { label: 'Напряжение накопителя', get: (m) => m.u, min: 0, max: 12, band: [0, 1], fmt: fmtVolts },

    parts: L.parts,
    wires: L.wires,
    build: (c, P) => Rig.build(c, P),
    apply: (refs, P, c) => Rig.apply(c, refs, P),

    // Ключ ввода щёлкает сам: иначе разряд пришлось бы ловить вручную, а
    // измерять надо именно его. Отсчёт начинается в момент снятия питания и
    // останавливается, когда напряжение упало ниже вольта.
    tick(dt, P, m) {
      P.SA1.t = (P.SA1.t || 0) + dt;
      const on = (P.SA1.t % 6) < 3;
      // Замер держится до следующего разряда, а не стирается на время
      // зарядки: иначе условие победы существует доли секунды в конце
      // каждого цикла и удержать его невозможно в принципе.
      if (!on && P.SA1.closed) { P.SA1.since = 0; P.SA1.peak = m.u; P.SA1.down = undefined; }
      P.SA1.closed = on;
      if (!on) {
        P.SA1.since = (P.SA1.since || 0) + dt;
        if (P.SA1.down === undefined && m.u < 1.0) P.SA1.down = P.SA1.since;
      }
    },

    read(sol, refs, P) {
      const u = sol.nodeVoltage.BUS || 0;
      const down = P.SA1.down;
      const peak = P.SA1.peak === undefined ? 0 : P.SA1.peak;
      return {
        u, down, peak,
        on: !!P.SA1.closed,
        iBleed: Math.abs(sol.componentCurrent.R1 || 0),
        empty: !P.R1.content,
        jumper: !!P.R1.content && P.R1.content.kind === 'jumper',
        r: P.R1.content && P.R1.content.value ? P.R1.content.value : 0,
        ok: down !== undefined && down >= 2 && down <= 4 && peak > 11,
      };
    },

    status(m) {
      if (m.empty) return ['Разрядного нет: после снятия питания накопитель остаётся заряженным насовсем.', 'neutral'];
      if (m.jumper) return ['Перемычка разряжает мгновенно — и всё время работы коротит накопитель накоротко.', 'bad'];
      if (m.ok) return ['Накопитель сбрасывается за ' + m.down.toFixed(1) + ' с — в норме.', 'good'];
      if (m.down === undefined) return ['Разряд идёт слишком медленно: за отведённое время накопитель до вольта не падает.', 'warn'];
      if (m.down < 2) return ['Разряд слишком быстрый: разрядный резистор мал, и он всё время жжёт ток впустую.', 'warn'];
      return ['Разряд слишком долгий: разрядный резистор велик.', 'warn'];
    },

    goal(m) {
      if (m.empty) return { ok: false, note: 'Разрядный резистор не поставлен.' };
      if (m.down === undefined) return { ok: false, note: 'До одного вольта накопитель ещё не упал' };
      return { ok: m.ok, note: 'Сброс за ' + m.down.toFixed(1) + ' с, нужно 2…4 с' };
    },

    score(m) { return m.ok ? bandScore(m.down, 3.0, 0.34) : 0; },
    scoreNote(m) { return 'Разрядный ' + fmtOhms(m.r) + ': сброс за ' + (m.down || 0).toFixed(1) + ' с'; },

    meter(m) {
      return [
        ['На накопителе', fmtVolts(m.u), m.on ? '' : 'warn'],
        ['Питание', m.on ? 'подано' : 'снято', m.on ? 'good' : 'warn'],
        ['Время сброса', m.down === undefined ? '—' : m.down.toFixed(1) + ' с', m.ok ? 'good' : 'warn'],
        ['Ток разрядного', m.empty ? '—' : fmtAmps(m.iBleed)],
        ['Нужно', '2…4 с до 1 В'],
      ];
    },
  }));
})();
