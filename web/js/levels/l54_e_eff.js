'use strict';
// Е-07 · Куда уходит мощность. Прямое продолжение согласования из
// измерительного тракта — и прямое ему возражение: там нагрузку подбирали под
// максимум мощности, здесь выясняется, что в этой точке ровно половина всего
// сгорает в линии. Два требования тянут в разные стороны, и в этом весь узел.

(() => {
  const L = Rig.rows({
    id: 'e_eff',
    board: DB.s.board,
    supply: { id: 'SUP', name: 'Ввод узла', label: '12 В', silk: 'G1', value: 12 },
    rated: 0.5,
    rows: [
      {
        id: 'LN', rated: 0.5,
        items: [
          { id: 'RL', kind: 'device', name: 'Сопротивление линии', silk: 'RL', value: 10, showValue: true, rated: { pMax: 12.0, tau: 1.5 } },
          {
            id: 'RN', kind: 'pot', name: 'Нагрузка на конце линии', silk: 'RN',
            value: 5, knob: 0,
            rated: { pMax: 6.0, tau: 1.5 },
            interact: {
              type: 'knob', hint: 'Крути колесом мыши или тяни вверх-вниз',
              map: (k) => Math.round(lerp(5, 200, clamp(k, 0, 1))),
            },
          },
        ],
      },
    ],
  });

  createLevel(LevelRegistry.register({
    id: 'e_eff',
    index: 68,
    title: 'Куда уходит мощность',
    teaches: 'КПД линии против максимума мощности',
    silk: 'EFF-085-68',
    diag: 'ДИАГНОСТИКА · Узел Е-07: линия греется сильнее нагрузки.',
    brief: 'Между шиной и потребителем десять ом линии, и они никуда не денутся. Нагрузку можно крутить. Нужно, чтобы до нагрузки доходило не меньше 85% всей мощности и при этом ей самой доставалось не меньше одного ватта.',
    lesson: 'Мощность, которую отдаёт источник, делится между линией и нагрузкой в той же пропорции, что и сопротивления. Когда нагрузка равна сопротивлению линии, нагрузка получает наибольшую возможную мощность — но ровно столько же в этот момент сгорает в самой линии, то есть половина всего уходит в тепло проводов. Чем нагрузка больше линии, тем выше доля дошедшего, но тем меньше и сам ток, а с ним и абсолютная мощность. Поэтому «максимум мощности» и «максимум КПД» — это две разные настройки, и выбирать приходится, какая нужна.',
    reveal: 'Подогрев кабельного ввода. Он грелся сильнее, чем грел, — линию к нему тянули по остаточному принципу, из того, что было.',
    hints: [
      'Покрути ручку от края до края и смотри сразу на две строки: долю и ватты на нагрузке.',
      'Доля дошедшего — это сопротивление нагрузки, делённое на сумму нагрузки и линии.',
      'При 85% нагрузка должна быть примерно вшестеро больше линии, то есть около шестидесяти ом. Дальше растёт доля, но падают ватты.',
    ],
    codex: ['power', 'ohm', 'series', 'resistor'],
    vmax: 12.0,
    hold: 2.5,
    scale: DB.s.scale,
    board: DB.s.board,
    map: { pos: vec(215, 795), radius: 900, color: hex(0xffc46b), from: ['e_share', 'e_line'], icon: { kind: 'pot' } },
    goalText: 'До нагрузки доходит не меньше 85% мощности, и на ней не меньше 1 Вт.',
    scope: { label: 'Доля мощности в нагрузке', get: (m) => m.eff, min: 0, max: 1, band: [0.85, 1], fmt: (v) => Math.round(v * 100) + '%' },

    parts: L.parts,
    wires: L.wires,
    build: (c, P) => Rig.build(c, P),
    apply: (refs, P, c) => Rig.apply(c, refs, P),

    read(sol, refs, P) {
      const i = Math.abs(sol.componentCurrent.RN || 0);
      const uLoad = sol.nodeVoltage.LN_1 || 0;
      const uLine = (sol.nodeVoltage.VCC || 0) - uLoad;
      const pLoad = uLoad * i;
      const pLine = uLine * i;
      const eff = (pLoad + pLine) > 1e-9 ? pLoad / (pLoad + pLine) : 0;
      return {
        i, uLoad, uLine, pLoad, pLine, eff,
        r: P.RN.value,
        ok: eff >= 0.85 && pLoad >= 1.0,
      };
    },

    status(m) {
      if (m.ok) return ['Доходит ' + Math.round(m.eff * 100) + '% при ' + fmtWatts(m.pLoad) + ' на нагрузке. Оба условия сошлись.', 'good'];
      if (m.eff < 0.85) return ['Слишком много сгорает в линии: нагрузка мала по сравнению с ней. Прибавь сопротивление.', 'warn'];
      return ['Доля хорошая, но ватт на нагрузке уже не хватает: ток стал слишком мал. Убавь сопротивление.', 'warn'];
    },

    goal(m) {
      if (m.eff < 0.85) return { ok: false, note: 'Доходит ' + Math.round(m.eff * 100) + '%, нужно не меньше 85%' };
      return { ok: m.pLoad >= 1.0, note: 'На нагрузке ' + fmtWatts(m.pLoad) + ', нужно не меньше 1 Вт' };
    },

    score(m) { return m.ok ? clamp((m.eff - 0.5) / 0.45, 0, 1) : 0; },
    scoreNote(m) { return 'Ручка на ' + fmtOhms(m.r) + ': до нагрузки доходит ' + Math.round(m.eff * 100) + '% и ' + fmtWatts(m.pLoad); },

    meter(m) {
      return [
        ['Доходит до нагрузки', Math.round(m.eff * 100) + '%', m.eff >= 0.85 ? 'good' : 'warn'],
        ['Мощность нагрузки', fmtWatts(m.pLoad), m.pLoad >= 1 ? 'good' : 'warn'],
        ['Сгорает в линии', fmtWatts(m.pLine)],
        ['Ручка', fmtOhms(m.r)],
        ['Ток', fmtAmps(m.i)],
      ];
    },
  }));
})();
